/**
 * Wire protocol constants.
 * Keys are shortened for bandwidth efficiency.
 */

// Client -> Server operations
export const Op = {
  JOIN: 'j',
  AUTH: 'au',
  UNAUTH: 'ua',
  SET: 's',
  UPDATE: 'u',
  DELETE: 'd',
  PUSH: 'p',
  SUBSCRIBE: 'sb',
  UNSUBSCRIBE: 'us',
  ONCE: 'o',
  ON_DISCONNECT: 'od',
  LEAVE: 'l',
  TRANSACTION: 'tx',
} as const;

// Transaction operation types (used within tx ops array)
export const TxOp = {
  SET: 's',
  UPDATE: 'u',
  DELETE: 'd',
  CONDITION: 'c',
} as const;

export type TxOpType = (typeof TxOp)[keyof typeof TxOp];

// OnDisconnect actions
export const OnDisconnectAction = {
  SET: 's',
  UPDATE: 'u',
  DELETE: 'd',
  CANCEL: 'c',
} as const;

// Server -> Client event types (wire format)
// Server now sends 'put' and 'patch' events; client generates child_* events locally
export const ServerEventType = {
  PUT: 'put',
  PATCH: 'patch',
} as const;

export type ServerEventTypeValue = (typeof ServerEventType)[keyof typeof ServerEventType];

// Client-side event types (API-facing)
// These are generated by the client from put/patch events
export type EventType = 'value' | 'child_added' | 'child_changed' | 'child_removed' | 'child_moved';

// Map client event types to short form for subscribe message
export const eventTypeToShort: Record<EventType, string> = {
  value: 'v',
  child_added: 'ca',
  child_changed: 'cc',
  child_removed: 'cr',
  child_moved: 'cm',
};

